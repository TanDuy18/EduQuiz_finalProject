const LABELS: ("A" | "B" | "C" | "D")[] = ["A", "B", "C", "D"];

function figOpts(id: string, texts: [string, string, string, string], correctIdx: number): QuestionOptionRecord[] {
  return texts.map((content, idx) => ({
    id: `${id}_opt_${LABELS[idx]}`,
    label: LABELS[idx],
    content,
    isCorrect: idx === correctIdx,
    orderIndex: idx + 1,
  }));
}

function figQ(
  id: string,
  code: string,
  quizId: string,
  orderIndex: number,
  subjectName: string,
  levelCode: EducationLevelCode,
  content: string,
  opts: [string, string, string, string],
  correctIdx: number,
  explanation: string,
  difficulty: "EASY" | "MEDIUM" | "HARD" = "MEDIUM",
): QuestionRecord {
  return {
    id,
    code,
    quizId,
    subjectName,
    levelCode,
    content,
    type: "SINGLE_CHOICE",
    difficulty,
    explanation,
    score: 1,
    orderIndex,
    approvalStatus: "APPROVED",
    options: figOpts(id, opts, correctIdx),
    dataSource: "FIGMA_REFERENCE",
  };
}

